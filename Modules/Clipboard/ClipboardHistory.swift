import Cocoa

struct ClipboardEntry: Codable, Equatable {
    let text: String
    let date: Date
    let sourceApp: String?
}

/// Text clipboard history persisted as JSON in Application Support, newest first, deduplicated.
/// macOS has no pasteboard-change notification, so `ClipboardWatcher` polls `changeCount`
/// (an integer read, no IPC payload) twice a second.
final class ClipboardHistory {
    static let limit = 200
    /// Larger copies (logs, files read as text) are skipped: they bloat the JSON that is rewritten on every copy.
    static let maxEntryLength = 100_000
    private(set) var entries = [ClipboardEntry]()
    private let fileURL: URL

    init(fileURL: URL = ClipboardHistory.defaultURL) {
        self.fileURL = fileURL
        load()
    }

    static var defaultURL: URL {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Nexo", isDirectory: true)
        return base.appendingPathComponent("clipboard.json")
    }

    func add(_ text: String, sourceApp: String?, now: Date = Date()) {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty, text.utf16.count <= Self.maxEntryLength else { return }
        entries.removeAll { $0.text == text }
        entries.insert(ClipboardEntry(text: text, date: now, sourceApp: sourceApp), at: 0)
        if entries.count > Self.limit { entries.removeLast(entries.count - Self.limit) }
        save()
    }

    func remove(at index: Int) {
        guard entries.indices.contains(index) else { return }
        entries.remove(at: index)
        save()
    }

    func clear() {
        entries.removeAll()
        save()
    }

    func search(_ query: String) -> [ClipboardEntry] {
        let query = query.trimmingCharacters(in: .whitespaces)
        guard !query.isEmpty else { return entries }
        return entries.filter { $0.text.localizedCaseInsensitiveContains(query) }
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else { return }
        entries = decoded
    }

    private func save() {
        // umask 077 makes the atomic write's temp file owner-only from the start, not just after a chmod.
        let previousMask = umask(0o077)
        defer { umask(previousMask) }
        do {
            try FileManager.default.createDirectory(at: fileURL.deletingLastPathComponent(), withIntermediateDirectories: true,
                attributes: [.posixPermissions: 0o700])
            try JSONEncoder().encode(entries).write(to: fileURL, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
        } catch {
            NSLog("Nexo: clipboard history save failed: \(error)")
        }
    }
}

/// Polls the general pasteboard and records new text, skipping secrets.
final class ClipboardWatcher {
    /// Password managers mark copied secrets with these types (nspasteboard.org conventions).
    static let skippedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    static let defaultExcludedApps = ["com.bitwarden.desktop", "io.ente.auth.mac", "com.agilebits.onepassword7", "com.1password.1password", "com.apple.keychainaccess", "com.apple.Passwords"]

    private let history: ClipboardHistory
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    var excludedApps: () -> [String] = { ClipboardWatcher.defaultExcludedApps }

    init(history: ClipboardHistory) {
        self.history = history
    }

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        // Short interval so the frontmost app read below is still the one that copied (secret filtering).
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Call right after Nexo writes to the pasteboard itself, so that write isn't recorded as a copy.
    func markOwnWrite() {
        lastChange = NSPasteboard.general.changeCount
    }

    static func shouldSkip(types: [String], sourceApp: String?, excluded: [String]) -> Bool {
        if types.contains(where: skippedTypes.contains) { return true }
        if let sourceApp, excluded.contains(sourceApp) { return true }
        return false
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !Self.shouldSkip(types: types, sourceApp: source, excluded: excludedApps()),
              let text = pasteboard.string(forType: .string) else { return }
        history.add(text, sourceApp: source)
    }
}
